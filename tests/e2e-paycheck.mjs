// Add-a-job with a semi-monthly hourly schedule (each check worked out from its own pay window).
// Run: node tests/e2e-paycheck.mjs [screenshot-folder]   (site served at http://localhost:8765)
import { chromium, devices } from "playwright";

const BASE = "http://localhost:8765/";
const OUT = process.argv[2] || "";
const results = []; let failures = 0;
const ok = (n, c, x) => { results.push((c ? "  ok  " : "  FAIL") + " - " + n + (c || x === undefined ? "" : "  [" + x + "]")); if (!c) failures++; };
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const pinClock = () => { const R = Date; const f = new R(2026, 10, 25, 18, 0, 0).getTime(); class D extends R { constructor(...a) { if (!a.length) super(f); else super(...a); } static now() { return f; } } window.Date = D; };

const browser = await chromium.launch();
const ctx = await browser.newContext({ ...devices["iPhone 14"], colorScheme: "light" });
await ctx.addInitScript(pinClock);
const p = await ctx.newPage();
const errors = []; p.on("pageerror", (e) => errors.push(e.message));
const tap = async (s) => { await p.locator(s).first().click(); await sleep(300); };
await p.goto(BASE); await sleep(400);
await tap('[data-act="demo"]');
await p.fill('[data-inp="onbBal"][data-i="0"]', "1250");
await tap('[data-act="onbDone"]'); await sleep(700);
await tap('.avatar[data-act="tab"]'); await tap('[data-act="addUSHolidays"]'); await sleep(300);
await tap('.tb[data-v="plan"]'); await tap('[data-act="planSeg"][data-v="pay"]');
await tap('[data-act="editJob"]'); await sleep(400);
await p.fill("#jName", "West Coast Magnetics"); await p.fill("#jRate", "23"); await p.fill("#jHours", "40"); await p.fill("#jTax", "20");
ok("biweekly: no pay-window question", await p.locator("#jWin").count() === 0);
await p.selectOption("#fFreq", "semimonthly"); await sleep(250);
ok("semi-monthly hourly asks which hours each check pays", await p.locator("#jWin").count() === 1);
ok("paydays default to 15th and last day", (await p.inputValue("#fMd1")) === "15" && (await p.inputValue("#fMd2")) === "31");
ok("weekend/holiday paydays default to the business day before", (await p.inputValue("#fShift")) === "before");
await p.selectOption("#jWin", "10,25"); await p.fill("#fStart", "2026-11-01"); await p.dispatchEvent("#fStart", "input"); await p.locator("#jRate").dispatchEvent("input"); await sleep(250);
const est = await p.locator("#jEst").innerText();
ok("preview lists the next paydays with their hours", est.includes("Next paydays") && est.includes("Nov 11 – Nov 25") && est.includes("88 h"), est.slice(0, 300));
ok("preview shows the range of checks", /Each check\s*\$[\d,.]+ – \$[\d,.]+/.test(est), est.slice(0, 120));
ok("Mon Nov 30 check is $1,619.20 take-home (88 h × $23 − 20%)", est.includes("Mon, Nov 30") && est.includes("$1,619.20"));
if (OUT) await p.screenshot({ path: `${OUT}/job-form.png` });
await p.evaluate(() => { const b = document.querySelector("#sheet .sbody"); b.scrollTop = b.scrollHeight; }); await sleep(200);
if (OUT) await p.screenshot({ path: `${OUT}/job-form-bottom.png` });
await tap('#sheet [data-act="saveJob"]'); await sleep(500);
const rule = await p.evaluate(() => Object.values(JSON.parse(localStorage.getItem("pocket-demo-v1")).rules).find((r) => r.kind === "paycheck"));
ok("job saved with its pay windows", rule && JSON.stringify(rule.meta.periodEnds) === "[10,25]" && rule.meta.paidHolidays === true && rule.freq === "semimonthly", JSON.stringify(rule && rule.meta));
const checks = await p.evaluate(async () => { const F = await import("/js/finance.js"); const { __test } = await import("/js/app.js");
  return F.buildItems(__test.data(), "2026-12-01", "2027-03-31").filter((i) => i.kind === "paycheck").map((i) => [i.date, i.amount, i.payHours]); });
const m = Object.fromEntries(checks.map(([d, a, h]) => [d, [a, h]]));
ok("calendar: Dec 15 pays 88 h", m["2026-12-15"] && m["2026-12-15"][1] === 88, JSON.stringify(checks));
ok("calendar: Dec 31 pays 88 h (Dec 11–25 has 11 weekdays, Christmas paid)", m["2026-12-31"] && m["2026-12-31"][1] === 88);
ok("calendar: Feb 15 2027 (Presidents Day) is paid Fri Feb 12", !!m["2027-02-12"] && !m["2027-02-15"]);
ok("calendar: Mar 15 2027 is the small one (72 h, $1,324.80)", m["2027-03-15"] && m["2027-03-15"][0] === 1324.8);
await tap('.tb[data-v="calendar"]'); await tap('[data-act="month"][data-v="1"]'); await tap('[data-act="selDay"][data-v="2026-12-15"]');
await tap('.item[data-act="openOcc"]'); await sleep(400);
ok("tapping a payday shows the hours it covers", (await p.locator("#sheet").innerText()).includes("Pays Nov 26 – Dec 10 · 88 hours"));
if (OUT) await p.screenshot({ path: `${OUT}/payday-sheet.png` });
await tap('#sheet [data-act="closeSheet"]');
await tap('.tb[data-v="plan"]'); await tap('[data-act="planSeg"][data-v="pay"]');
ok("Paychecks list calls it an average check", (await p.locator("#app").innerText()).includes("average check"));
await tap('[data-act="editJob"][data-id]'); await sleep(300);
ok("editing keeps the chosen pay window", (await p.inputValue("#jWin")) === "10,25" && await p.locator("#jPaidHol").isChecked());
ok("no JavaScript errors", errors.length === 0, errors.join(" | "));
await browser.close();
console.log(results.join("\n")); console.log(`\n${results.length - failures} passed, ${failures} failed`);
process.exit(failures ? 1 : 0);
